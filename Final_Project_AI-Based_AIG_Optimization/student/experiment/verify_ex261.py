#!/usr/bin/env python3
"""Verify ex261 = bit_reverse_10((A+1)*(B+1) mod 1024) and generate Verilog."""
import sys
sys.set_int_max_str_digits(200000)
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BENCH = ROOT / "benchmarks"
OUT   = ROOT / "student"

def read_truth(path):
    lines = [l for l in Path(path).read_text().strip().splitlines() if l.strip()]
    # Format: each line is one output bit string of length 2^n_in
    n_entries = len(lines[0])
    n_in = n_entries.bit_length() - 1  # 2^n_in = n_entries
    return n_in, lines

def brev10(x):
    result = 0
    for i in range(10):
        result |= ((x >> i) & 1) << (9 - i)
    return result

def verify():
    n_in, outs = read_truth(BENCH / "ex261.truth")
    n_out = len(outs)
    total = len(outs[0])
    print(f"ex261: {n_in} inputs, {n_out} outputs, {total} entries")

    correct = 0
    wrong = []
    for i in range(total):  # total defined above
        A = (i >> 5) & 0x1F
        B = i & 0x1F
        pred = brev10(((A + 1) * (B + 1)) & 0x3FF)
        actual = 0
        for b in range(n_out):
            actual |= int(outs[b][i]) << (n_out - 1 - b)
        if pred == actual:
            correct += 1
        elif len(wrong) < 10:
            wrong.append((i, A, B, pred, actual))

    print(f"Formula match: {correct}/{total} ({100*correct/total:.2f}%)")
    if wrong:
        print("Mismatches:")
        for idx, A, B, pred, actual in wrong:
            print(f"  i={idx} A={A} B={B}: pred={pred:010b} actual={actual:010b}")
    return correct == total

def gen_verilog():
    v = """\
// ex261: output = bit_reverse_10((A+1)*(B+1) mod 1024)
// Inputs: in[9:5]=A (5-bit), in[4:0]=B (5-bit)
// Output: out[9:0]
// Generated by student/verify_ex261.py
module ex261(input [9:0] in, output [9:0] out);
  wire [4:0] A = in[9:5];
  wire [4:0] B = in[4:0];
  // (A+1)*(B+1): 6-bit * 6-bit = at most 12 bits, keep low 10
  wire [11:0] prod_full = ({1'b0, A} + 6'd1) * ({1'b0, B} + 6'd1);
  wire [9:0]  prod = prod_full[9:0];
  // Bit-reverse: out[i] = prod[9-i]
  assign out[0] = prod[9];
  assign out[1] = prod[8];
  assign out[2] = prod[7];
  assign out[3] = prod[6];
  assign out[4] = prod[5];
  assign out[5] = prod[4];
  assign out[6] = prod[3];
  assign out[7] = prod[2];
  assign out[8] = prod[1];
  assign out[9] = prod[0];
endmodule
"""
    dst = OUT / "ex261.v"
    dst.write_text(v)
    print(f"Wrote {dst}")

if __name__ == "__main__":
    ok = verify()
    if ok:
        print("Formula verified 100% — generating Verilog")
        gen_verilog()
    else:
        print("Formula NOT 100% correct — need to investigate mismatches")
        sys.exit(1)
